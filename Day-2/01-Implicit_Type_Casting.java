class implicit_type_casting
{
    public static void main(String[] args)
    {

        int a = 10;

        double b = a;

        System.out.println(b);


        ////////////////////////////////////////
        

        byte c = 56;
        int d = c;  

        System.out.println(d);

        // Note: We cannot able to convert int to byte using Implicit Type Casting


        ////////////////////////////////////////
        

        


    }
}