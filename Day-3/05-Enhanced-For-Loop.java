class enhanced_for_loop
{
    public static void main(String[] args)
    {
        String[] employees = {
            "Saikiran",
            "Abhishek",
            "Niranjan",
            "Datta",
            "Akash",
            "Uday"
        };


        for (String name : employees )
        {
            System.out.println(name);
        }
    }
}